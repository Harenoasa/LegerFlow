-- 10. 导入后自检（结果应全部为 0）
-- ============================================================
SELECT '订单总额与明细不一致' AS check_item, COUNT(*) AS bad_rows
FROM orders o
WHERE o.total_amount <> (SELECT COALESCE(SUM(i.item_amount), 0) FROM order_item i WHERE i.order_id = o.id)
UNION ALL
SELECT '订单应付金额公式不成立', COUNT(*)
FROM orders
WHERE pay_amount <> total_amount - discount_amount + freight_amount
UNION ALL
SELECT '订单行金额公式不成立', COUNT(*)
FROM order_item
WHERE item_amount <> unit_price * quantity OR pay_amount <> item_amount - discount_amount
UNION ALL
SELECT '成功支付金额与订单不符', COUNT(*)
FROM orders o
WHERE o.order_status IN (10, 20, 30, 50, 60)
  AND o.pay_amount <> (SELECT COALESCE(SUM(p.amount), 0) FROM payment_order p WHERE p.order_no = o.order_no AND p.status = 1)
UNION ALL
SELECT '退款金额超过支付金额', COUNT(*)
FROM orders o
WHERE (SELECT COALESCE(SUM(r.amount), 0) FROM refund_order r WHERE r.order_no = o.order_no AND r.status = 2) > o.pay_amount
UNION ALL
SELECT '库存出现负数', COUNT(*)
FROM inventory
WHERE available_stock < 0 OR locked_stock < 0 OR sold_stock < 0
UNION ALL
SELECT '优惠券与订单双向不一致', COUNT(*)
FROM user_coupon uc
LEFT JOIN orders o ON o.id = uc.order_id
WHERE uc.status = 1 AND (o.id IS NULL OR o.coupon_id <> uc.id)
UNION ALL
SELECT '订单引用的券未标记已使用', COUNT(*)
FROM orders o
LEFT JOIN user_coupon uc ON uc.id = o.coupon_id
WHERE o.coupon_id IS NOT NULL AND (uc.id IS NULL OR uc.status <> 1 OR uc.order_id <> o.id);
